import {chromium} from '../generated/browser/node_modules/playwright/index.mjs';
import {getCountries,getCountryCallingCode} from 'libphonenumber-js/max';
import {readFile,mkdir} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {randomBytes} from 'node:crypto';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..'),require=createRequire(import.meta.url);
const {parse}=require(resolve(root,'backend/node_modules/dotenv'));
const env=parse(await readFile(resolve(root,'backend/.env')));
if(!['localhost','127.0.0.1'].includes(new URL(env.DATABASE_URL).hostname))throw new Error('Local only');
const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
try {
  const context=await browser.newContext({viewport:{width:1440,height:1000}}),page=await context.newPage();
  const directory=resolve(root,'platform/generated/local');await mkdir(directory,{recursive:true});
  let submissions=0;page.on('request',request=>{if(request.url().endsWith('/platform/access-requests')&&request.method()==='POST')submissions++;});
  await page.goto('http://127.0.0.1:5173');await page.getByRole('button',{name:'Solicitar acceso empresarial',exact:true}).click();
  await page.getByLabel('Empresa',{exact:true}).fill('Prueba de teléfono internacional');
  await page.getByLabel('Tu nombre',{exact:true}).fill('Contacto de prueba');
  await page.screenshot({path:resolve(directory,'solicitud-paso-1-desktop.png'),fullPage:true});
  await page.getByRole('button',{name:'Continuar',exact:true}).click();
  await page.getByRole('button',{name:'País o territorio',exact:true}).waitFor();
  if(submissions!==0)throw new Error('First step submitted the request');
  await page.getByRole('button',{name:'Volver al paso anterior',exact:true}).click();
  if(await page.getByLabel('Empresa',{exact:true}).inputValue()!=='Prueba de teléfono internacional')throw new Error('Business data lost when returning');
  await page.getByRole('button',{name:'Continuar',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'País o territorio',exact:true}).click();
  const countries=await page.getByRole('option').evaluateAll(options=>options.map(option=>({country:option.dataset.country,text:option.textContent})));
  if(countries.length!==getCountries().length||new Set(countries.map(item=>item.country)).size!==getCountries().length)throw new Error('Incomplete country list');
  for(const country of getCountries())if(!countries.find(item=>item.country===country&&item.text.includes(`+${getCountryCallingCode(country)}`)))throw new Error('Missing country prefix');
  await page.getByRole('combobox',{name:'Buscar país o código'}).fill('espana');
  await page.locator('[role="option"][data-country="ES"]').waitFor();
  await page.getByRole('combobox',{name:'Buscar país o código'}).press('Escape');
  await page.getByRole('button',{name:'País o territorio',exact:true}).click();
  await page.getByRole('combobox',{name:'Buscar país o código'}).fill('canada');
  await page.screenshot({path:resolve(directory,'selector-pais-mobile.png'),fullPage:true});
  await page.getByRole('combobox',{name:'Buscar país o código'}).press('Enter');
  const email=`phone-${randomBytes(4).toString('hex')}@example.test`;
  await page.getByLabel('Correo',{exact:true}).fill(email);
  await page.getByLabel('Contraseña',{exact:true}).fill('Local-phone-test-password-2026');
  await page.getByLabel('Número nacional',{exact:true}).fill('2025550123');
  await page.getByRole('button',{name:'Enviar solicitud',exact:true}).click();
  await page.getByText('Revisa el número de teléfono y el país elegido.',{exact:true}).waitFor();
  await page.getByLabel('Número nacional',{exact:true}).fill('416 555 0123');
  await page.getByLabel('Correo',{exact:true}).click();
  await page.screenshot({path:resolve(directory,'telefono-pais-mobile.png'),fullPage:true});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Mobile overflow');
  const sent=page.waitForRequest(request=>request.url().endsWith('/platform/access-requests')&&request.method()==='POST');
  await page.getByRole('button',{name:'Enviar solicitud',exact:true}).click();
  const request=(await sent).postDataJSON();
  if(request.phone!=='+14165550123'||request.phone_country!=='CA')throw new Error('Country normalization failed');
  await page.getByRole('heading',{name:'Solicitud recibida',exact:true}).waitFor();
  await page.getByRole('button',{name:'Ya tengo acceso',exact:true}).click();
  await page.getByLabel('Correo',{exact:true}).waitFor();
  const login=await context.request.post('http://127.0.0.1:5173/api/v1/auth/login',{data:{email:env.ADMIN_EMAIL,password:env.ADMIN_PASSWORD}});
  if(!login.ok())throw new Error('Admin login failed');
  const response=await context.request.get('http://127.0.0.1:5173/api/v1/platform/admin/access-requests');
  const application=(await response.json()).items.find(item=>item.email===email);
  if(!application||application.phone!=='+14165550123'||application.phone_country!=='CA'||application.status!=='pending')throw new Error('Country or phone not persisted');
  console.log(`Phone form OK: ${countries.length} countries/territories, all prefixes, Canada/US separation, mobile layout and normalized pending request persisted.`);
} finally{await browser.close();}
